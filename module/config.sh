# OFM 本机网关模块配置
# 修改后重启手机，或在 KernelSU 里点模块动作按钮选「重启服务」生效。

# 监听端口。0 = 用服务自己记住的端口（首次默认 18900，被占用时自动顺延并记住）。
# 填具体端口号则强制用它。
PORT=15656

# 局域网访问：0 只给本机（127.0.0.1），1 额外开一个局域网中继。
# 中继与本机监听是两扇门：它有自己的 LAN Key，地址与 Key 见 status / info。
# 服务本体的监听地址由上游固定为回环地址，不再可配。
LAN=0

# 局域网中继端口。0 = 由系统自动分配（实际端口见 status；自动分配时取自服务启动日志）。
LAN_PORT=0

# 开机自启：1 开启，0 关闭
AUTOSTART=1

# 日志保留天数。日志按天分文件（$DATA_DIR/logs/ofm-YYYY-MM-DD.log），
# 只保留最近这么多天，更早的自动清理。
LOG_KEEP_DAYS=14

# 数据目录（settings.json、统计、渠道账号都放这里）
DATA_DIR=/data/adb/ofm
